// SC Prism — governance bundle generation.
// The Review page's "Activate" writes these real YAML files into the vault's
// `governance/` folder (ADR-014: the vault is the single source of truth).
// Live enforcement already flows from the interview store (sensitive words →
// SCPRISM_SENSITIVE force-local routing, verify command → engine --tier1, the
// rest → the Companion charter); these files are the durable, human-readable
// record of that governance, versioned with your vault.

import { PRIORITY_LABEL, ROLE_HATS, SIGNOFFS, type InterviewState } from './interview'
import { primaryDisplayName, primaryModelLabel, type Settings } from './settings'

export interface GovFile {
  relpath: string
  content: string
}

function yamlList(items: string[], indent = '  '): string {
  if (items.length === 0) return `${indent}[]`
  return items.map((i) => `${indent}- ${JSON.stringify(i)}`).join('\n')
}

/** Build the full governance bundle from the captured answers. */
export function buildGovernanceBundle(iv: InterviewState, settings: Settings): GovFile[] {
  const companion = primaryDisplayName(settings)
  const model = primaryModelLabel(settings)
  const roles = ROLE_HATS.filter((r) => iv.roles.includes(r))
  const gates = SIGNOFFS.filter((s) => iv.signoffs.includes(s.id))
  const priorities = iv.priorities.map((p) => PRIORITY_LABEL[p].toLowerCase())

  const files: GovFile[] = []

  files.push({
    relpath: 'governance/business.yaml',
    content:
      `# Business context — who you are (drives every plan the co-founder makes).\n` +
      `business:\n` +
      `  description: ${JSON.stringify(iv.business || '')}\n` +
      `  company: ${JSON.stringify(iv.companyName || '')}\n` +
      `  website: ${JSON.stringify(iv.website || '')}\n` +
      `  departments:\n${yamlList(iv.departments, '    ')}\n` +
      `  team_size: ${JSON.stringify(iv.teamSize || '')}\n` +
      `  budget: ${JSON.stringify(iv.budget || '')}\n`,
  })

  files.push({
    relpath: 'governance/companion.yaml',
    content:
      `# Your co-founder agent — the primary that plans, drafts and reviews.\n` +
      `companion:\n` +
      `  name: ${JSON.stringify(companion)}\n` +
      `  model: ${JSON.stringify(model)}\n` +
      `  rule: draft-then-confirm   # nothing runs without your approval (ADR-007)\n`,
  })

  files.push({
    relpath: 'governance/roles.yaml',
    content:
      `# Roles & access (RBAC/ABAC) — the hats you wear.\n` +
      `roles:\n${yamlList(roles)}\n`,
  })

  files.push({
    relpath: 'governance/gates.yaml',
    content:
      `# Sign-off gates — actions that always wait for your explicit approval.\n` +
      `gates:\n${yamlList(gates.map((g) => g.gate))}\n`,
  })

  files.push({
    relpath: 'governance/hooks.yaml',
    content:
      `# Enforcement hooks — deterministic policy (not instructions to a model).\n` +
      `hooks:\n` +
      `  - id: block-destructive\n` +
      `    on: PreToolUse\n` +
      `    deny: ["rm -rf", "drop table"]\n` +
      `  - id: never-touch-guard\n` +
      `    on: PreToolUse\n` +
      `    protect:\n${yamlList(iv.neverTouch, '      ')}\n`,
  })

  files.push({
    relpath: 'governance/sensitive.yaml',
    content:
      `# Force-local routing — anything matching these NEVER leaves this machine.\n` +
      `deny_cloud:\n` +
      `  builtin: ["password", "credential", "pii", "prod", "secret", "token"]\n` +
      `  yours:\n${yamlList(iv.sensitiveWords, '    ')}\n`,
  })

  files.push({
    relpath: 'governance/verify.yaml',
    content:
      `# Tier-1 gate — deterministic, 0-token; must PASS before any judgment.\n` +
      `tier1:\n` +
      `  command: ${JSON.stringify(iv.verifyCommand || '')}\n` +
      `  on_fail: short-circuit   # no cloud tokens spent when Tier-1 fails\n`,
  })

  files.push({
    relpath: 'governance/compliance.yaml',
    content:
      `# Compliance regimes folded into every plan and report.\n` +
      `compliance:\n${yamlList(iv.compliance)}\n`,
  })

  files.push({
    relpath: 'governance/routing.yaml',
    content:
      `# Gateway routing — priority order; routine work stays local.\n` +
      `routing:\n` +
      `  priority_order:\n${yamlList(priorities, '    ')}\n` +
      `  routine: local\n` +
      `  sensitive: local   # see sensitive.yaml\n`,
  })

  files.push({
    relpath: 'governance/README.md',
    content:
      `# Governance\n\n` +
      `Generated by SC Prism from your setup interview. These files are the ` +
      `durable record of your governance — the single source of truth (ADR-014).\n\n` +
      `Live enforcement runs on every call:\n` +
      `- **sensitive.yaml** words force LOCAL routing (never a cloud AI)\n` +
      `- **verify.yaml** command is the deterministic Tier-1 gate\n` +
      `- **gates.yaml** actions require your explicit sign-off\n` +
      `- **companion.yaml** — ${companion} drafts, you approve\n\n` +
      `Edit these by re-running the setup wizard, or ask ${companion} in chat.\n`,
  })

  return files
}
